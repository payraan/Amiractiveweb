import { log } from "@/lib/log";

// ═══ حالت پلتفرم: دمو یا واقعی ═══════════════════════════════
//
// ── چرا وجود دارد ──
// پلتفرم با پول مجازی لانچ می‌شود و بعداً به پول واقعی می‌رود. بدون یک
// سوییچ مرکزی، آن گذار یعنی دست‌زدن به ده فایل و امید داشتن که جایی جا
// نمانده — و «جایی که جا می‌ماند» در لایه‌ی پول یعنی یا پول کاربر گم
// می‌شود یا پول مجازی قابل برداشت می‌شود.
//
// ── چرا متغیر محیطی و نه یک ردیف در دیتابیس ──
// یک کلید در دیتابیس با یک کلیک اشتباه هم عوض می‌شود. این سوییچ تعیین
// می‌کند پول واقعی جابه‌جا شود یا نه، پس باید یک تغییرِ عمدی، قابل بازبینی
// و ثبت‌شده در تاریخچه‌ی دیپلوی باشد. عوض‌کردنش همچنان یک قدم است: یک
// متغیر در Railway.
//
// ── چرا پیش‌فرض «دمو» است و نه «واقعی» ──
// همان اصل fail-closed که در نشست و ادمین برقرار است. اگر متغیر ست نشود
// یا غلط تایپ شود:
//   • پیش‌فرض دمو  → بدترین حالت: پول واقعی موقتا حرکت نمی‌کند. برگشت‌پذیر.
//   • پیش‌فرض واقعی → بدترین حالت: موجودی دمو قابل برداشت می‌شود. **پول
//     واقعی از سیستم بیرون می‌رود بابت پولی که هرگز وارد نشده.**
// دو خطا هم‌وزن نیستند، پس پیش‌فرض سمت امن است.

export type PlatformMode = "demo" | "live";

let warned = false;

/**
 * حالت جاری. هر جای دیگری که خواست تصمیم بگیرد، باید از همین بپرسد —
 * خواندن مستقیم `process.env` در جای دیگر یعنی روزی یکی از آن‌ها جا
 * می‌ماند.
 */
export function platformMode(): PlatformMode {
  const raw = (process.env.PLATFORM_MODE ?? "").trim().toLowerCase();
  if (raw === "live") return "live";
  if (raw !== "demo" && raw !== "" && !warned) {
    // مقدار ناشناس یعنی کسی چیزی تایپ کرده و فکر می‌کند کار کرده. بی‌صدا
    // به دمو برگشتن، همان «شمارنده‌ی بی‌علت» است.
    warned = true;
    log.error("mode.unknown_value", { raw, using: "demo" });
  }
  return "demo";
}

export const isDemo = (): boolean => platformMode() === "demo";
export const isLive = (): boolean => platformMode() === "live";

/**
 * سهمیه‌ی ماهانه‌ی پول مجازی.
 *
 * ⚠️ عمدا سهمیه‌ی ماهانه و نه یک بخششِ یک‌باره‌ی بزرگ. با پانصد تتر مجازی و
 * حداقل شرط یک تتر، هیچ انتخابی سخت نیست — و وقتی انتخاب سخت نباشد،
 * مهارتی سنجیده نمی‌شود و کل داده‌ی رفتاری بی‌معنی می‌شود. کمیابی همان
 * چیزی است که پیش‌بینی را جدی می‌کند.
 *
 * و سهمیه‌ی ماهانه یک دلیل برای برگشتن می‌سازد — همان اصل «اهرم رایگان و
 * برابر: سهمیه‌ی ثابت، خریدنی نیست» که در سند محصول آمده.
 */
export const DEMO_ALLOWANCE = Number(process.env.DEMO_ALLOWANCE ?? 100);

/**
 * چرا یک کنش در حالت فعلی ممکن نیست — یا `null` اگر ممکن است.
 *
 * ⚠️ متن از اینجا می‌آید و نه از هر روت، تا سایت و ربات و مینی‌اپ **دقیقا
 * یک جمله** بگویند. سه متن متفاوت برای یک ممنوعیت، به کاربر می‌گوید
 * سیستم نمی‌داند دارد چه کار می‌کند.
 */
export const DEMO_BLOCKED: Record<"deposit" | "withdraw", string> = {
  deposit:
    "نارمون فعلا در نسخه‌ی دمو است و واریز تتر فعال نیست. " +
    "سهمیه‌ی ماهانه‌ی تو رایگان است و همه‌ی بخش‌ها با همان کار می‌کنند.",
  withdraw:
    "در نسخه‌ی دمو برداشت وجود ندارد، چون پولی وارد نشده که بیرون برود. " +
    "جایزه‌ی رقابت‌ها جدا و واقعی است.",
};

/**
 * وضعیت حالت برای رابط کاربری — همان چیزی که هر سه سطح نشان می‌دهند.
 *
 * ⚠️ **حتما به کاربر گفته می‌شود.** نسخه‌ی دمویی که کاربر ندانَد دمو است،
 * فریب است؛ و کسی که فکر کند پولش واقعی است، روزی می‌خواهد برداشتش کند.
 */
export function modeBanner(): {
  mode: PlatformMode;
  demo: boolean;
  title: string;
  body: string;
  allowance: number;
} | null {
  if (!isDemo()) return null;
  return {
    mode: "demo",
    demo: true,
    title: "نسخه‌ی دمو",
    body:
      `همه‌ی بخش‌ها با تتر مجازی کار می‌کنند و ماهانه ${DEMO_ALLOWANCE.toLocaleString("fa-IR")} ` +
      `تتر مجازی می‌گیری. پول واقعی هنوز وارد نشده — نه واریز، نه برداشت. ` +
      `رقابت و امتیاز واقعی‌اند و جایزه هم واقعی است.`,
    allowance: DEMO_ALLOWANCE,
  };
}

/** لاگ راه‌اندازی — یک بار در هر کولد استارت، تا در لاگ Railway معلوم باشد. */
let bootLogged = false;
export function logModeOnce(): void {
  if (bootLogged) return;
  bootLogged = true;
  log.warn("mode.active", {
    mode: platformMode(),
    allowance: DEMO_ALLOWANCE,
    // ⚠️ این خط تنها راه فهمیدنِ «چرا برداشت کار نمی‌کند» از روی لاگ است.
    depositEnabled: isLive(),
    withdrawEnabled: isLive(),
  });
}
