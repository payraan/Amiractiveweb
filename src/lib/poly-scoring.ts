// امتیازدهی صفر-انتظار ترید — جدا از poly.ts نگه داشته شده.
//
// poly.ts به db (و از آن به pg) وابسته است، پس نمی‌شود در کامپوننت کلاینت
// وارد شود. این دو تابع باید هم سمت سرور (تسویه) و هم سمت کلاینت (نمایش
// «اگر درست باشی چند امتیاز») در دسترس باشند، و کپی‌کردنشان یعنی دو تعریف
// که دیر یا زود از هم جدا می‌شوند — مثل همان کاری که ir-categories.ts برای
// دسته‌های بازار ایران می‌کند.
//
// برد = +(۱۰۰ − احتمال٪)، باخت = −احتمال٪. یعنی فقط «بهتر از بازار فهمیدن»
// امتیاز مثبت می‌سازد: حدس روی گزینه‌ی محتمل، برد کم و باخت سنگین دارد.

// هیچ گرد کردنی اینجا نیست، و عمدی است.
//
// قبلا برد و باخت جدا گرد می‌شدند: برای احتمال ۱.۴٪، برد round(98.6)=99 و
// باخت round(1.4)=1 — یعنی برد به بالا و باخت به پایین، هر دو به نفع کاربر.
// چون احتمال دو طرف مکمل‌اند، همیشه یک طرف بود که این سوگیری به سودش تمام
// می‌شد و کاربر هم از روی درصدِ نمایش‌داده‌شده می‌توانست تشخیصش بدهد.
// شبیه‌سازی: +۰.۴۵ امتیاز در هر پیش‌بینی، بدون هیچ مهارتی.
//
// با مقدار دقیق، برد + |باخت| همیشه دقیقا ۱۰۰ است و EV برای هر احتمالی صفر.
// گرد کردن فقط در لحظه‌ی نمایش انجام می‌شود، نه در محاسبه.
export function winPoints(probPct: number): number {
  return 100 - probPct;
}

export function losePoints(probPct: number): number {
  return -probPct;
}
